import { chromium } from 'playwright';
const b = await chromium.launch({ executablePath: process.env.PW_CHROME || undefined });
const c = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, serviceWorkers: 'block', locale: 'es-AR' });
await c.addInitScript(() => { window.NO_CLOUD = 1; });
const p = await c.newPage(); const errs = []; p.on('pageerror', e => errs.push(e.message));
const ok = (v, m) => console.log((v ? 'OK  ' : 'FALLA ') + m); const D = process.argv[2];
await p.goto('http://localhost:8776/'); await p.waitForTimeout(800);
await p.fill('#ob-name', 'Cris'); await p.click('#ob-go'); await p.waitForTimeout(400);
await p.click('#who'); await p.waitForTimeout(300); await p.click('.subtabs[data-group=pf] [data-st=set]'); await p.waitForTimeout(300);
ok(await p.isVisible('#pf-gap'), 'Ajustes: pausa para cambiar de lado'); ok(await p.isVisible('#pf-acc'), 'Ajustes: pausa para acomodarte');
await p.click('#pf-gap [data-v="6"]'); await p.click('#pf-acc [data-v="5"]');
ok(await p.evaluate(() => S.sideGap === 6 && S.prepSec === 5), 'se guardan');
await p.locator('#pf-gap').scrollIntoViewIfNeeded(); await p.screenshot({ path: D + '/pf-pausas.png' });
await p.evaluate(() => closeSheet()); await p.click('.subtabs[data-group=coach] [data-st=smart]'); await p.waitForTimeout(300);
await p.click('[data-fold=sm-opts]'); await p.waitForTimeout(200);
ok(await p.isVisible('#sm0-gap') || await p.isVisible('#sm-gap'), 'HIIT: opciones con las pausas');
await p.click('.subtabs[data-group=coach] [data-st=abs]'); await p.waitForTimeout(300);
const f = await p.$('#abs [data-fold]'); if (f) await f.click(); await p.waitForTimeout(200);
ok(await p.isVisible('#ab-acc') && await p.isVisible('#ab-gap'), 'Abdominales: opciones con las pausas');
await p.click('#ab-gap [data-v="2"]'); ok(await p.evaluate(() => S.sideGap === 2), 'abdominales: cambia la pausa');
console.log('errores', errs); await b.close();
