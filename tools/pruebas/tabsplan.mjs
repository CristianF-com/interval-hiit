import { chromium } from 'playwright';
const S = process.argv[2];
const b = await chromium.launch({ executablePath: process.env.PW_CHROME || undefined });
const ok = (v, m) => { console.log(v ? 'OK ' : 'FALLA ', m); if (!v) process.exitCode = 1; };
const c = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, serviceWorkers: 'block', locale: 'es-AR' });
await c.addInitScript(() => { window.NO_CLOUD = 1; });
const p = await c.newPage(); const errs = []; p.on('pageerror', e => errs.push(e.stack));
await p.goto('http://localhost:8776/'); await p.waitForTimeout(700);
await p.fill('#ob-name', 'C'); await p.click('#ob-go'); await p.waitForTimeout(300);
await p.click('[data-tab=plans]'); await p.waitForTimeout(300);
ok((await p.$$('[data-abl]')).length === 3, 'tres planes de abdominales en Planes');
await p.evaluate(() => document.querySelector('#abs-plans').scrollIntoView()); await p.screenshot({ path: S + '/absplan_0.png' });
await p.click('[data-abl="2"]'); await p.waitForTimeout(300);
ok(await p.evaluate(() => document.querySelector('#abs-lv [aria-pressed=true]').dataset.v) === '2', 'abre con intermedio elegido');
await p.click('#abs-ok'); await p.waitForTimeout(400);
await p.evaluate(() => { const s = getAbs(); s.day = 3; s.sessions = 3; setAbs(s); renderPlans(); document.querySelector('#abs-plans').scrollIntoView(); }); await p.waitForTimeout(300);
ok((await p.$$('[data-abd]')).length === 15, 'cronograma de 15 días');
await p.screenshot({ path: S + '/absplan_1.png' });
await p.click('[data-abd="3"]'); await p.waitForTimeout(300); ok(await p.$('#ai-go'), 'el día actual se puede empezar');
await p.evaluate(() => closeSheet()); await p.click('[data-abd="6"]'); await p.waitForTimeout(300); await p.screenshot({ path: S + '/absplan_2.png' });
ok(!errs.length, 'sin errores ' + errs.join('\n'));
await b.close();
